// scripts/update-all-employees-from-report.mjs
//
// Updates 526 existing employees from All_Employees_Report_UPDATED.xlsx, matched by
// **Record ID** — the column is literally the MongoDB `_id`, not a name or phone. This is the
// first bulk employee script in this repo that doesn't need the fuzzy phone/name-similarity
// machinery every earlier one required (scripts/employees-bulk-update.mjs,
// scripts/employee-salary-payables-import.mjs): that machinery existed specifically to guard
// against ambiguous identity when only a phone or a name was available, and a real _id removes
// the ambiguity outright. Match by `Employee.findById(recordId)`, full stop.
//
// This is UPDATE-ONLY. A Record ID that no longer resolves to a document (deleted since the
// report was generated) is reported and skipped — never recreated, since there is nothing in
// this sheet (no role history, no join date, no salary history) to safely reconstruct a deleted
// employee from.
//
// ─── THE [MERGED] ROWS — 31 of them, and why they need no special handling ──────────────────
//
// 31 rows have a name literally prefixed "[MERGED] " (e.g. "[MERGED] Ritu Afterservice",
// "[MERGED] SUNIL KUMAR BAIRWA") and Status "Inactive". Every one of them has a real, valid
// Record ID — these are exactly the duplicate-employee pairs identified earlier while building
// the salary-payables import (Sheetal/Sheetal Bhatiya, MOHIT SHAH, Dr Ashalata Roy, and — it
// turns out — Nishi/Ritu Afterservice and Sunil Bhairwa/Sunil Kumar Bairwa too), now manually
// resolved: one side of each pair was renamed with this marker and deactivated as the CRM's own
// record-keeping convention for "this was a duplicate, kept for audit, do not use". Because
// this script matches by _id and not by name or phone, these need no special branch at all —
// each one just updates the one specific document its Record ID names, exactly like any other
// row. They are reported as their own count in the dry run purely for visibility, not because
// they are handled differently.
//
// ─── FIELD MAPPING — every column, and which four are DELIBERATELY NEVER WRITTEN ────────────
//
//   Employee ID              -> employeeId   (only when the sheet gives a non-blank value)
//   Record ID                -> the match key itself; never written
//   Name                     -> name          (a plain rename — no similarity check needed,
//                                               see above; _id already proves identity)
//   Role                     -> role          (the SPECIFIC designation column — see the
//                                               case-collision note below; "Profile", the
//                                               broader legacy bucket, is kept only as
//                                               `legacyProfile` for this script's own log,
//                                               never written)
//   Profile                  -> NOT WRITTEN (legacy bucket, reference only)
//   Email                    -> email        (only when non-blank)
//   Phone                    -> phone        (only when non-blank)
//   Status                   -> isactive
//   Total Patients           -> NOT WRITTEN (a report-computed figure, not an Employee field)
//   Base Salary              -> salaryStructure.baseSalary
//   Salary Type              -> salaryStructure.salaryType    (only when non-blank)
//   Salary Effective From    -> salaryStructure.effectiveFrom (only when a valid date is given)
//   Incentive Rate           -> incentiveRate (only when the cell is not blank — several rows
//                                               have no value here at all, meaning "not given",
//                                               not "set it to zero")
//   Joined On                -> NOT WRITTEN (no matching field exists on the current Employee
//                                             model this script was written against — if one
//                                             has since been added, this is worth revisiting)
//   Last Updated             -> NOT WRITTEN (report metadata)
//
// THE GENERAL RULE, applied to every field above: a blank cell means "no opinion", never "clear
// this field" — an existing value is never overwritten with blank. Only a genuinely different,
// non-blank sheet value counts as a change.
//
// ─── CASE COLLISIONS — 43 of them, larger than the September list's 3 ───────────────────────
//
// The same phenomenon flagged in scripts/import-employees-sep2026.mjs, at greater scale: 43
// rows carry a Role that matches one of the OLD fixed-enum bucket names
// (Agent/Counsellor/Doctor/Technician/Implanter/Others/Hr) only in case — "IMPLANTER" vs
// "Implanter", "DOCTOR" vs "Doctor", and so on. Written EXACTLY AS GIVEN by default (never
// silently retitled); every one is listed in the dry run. Pass --normalize-role-case to
// title-case just these known historical names.
//
// ─── ONE DISCREPANCY WORTH KNOWING ABOUT ─────────────────────────────────────────────────────
//
// The report's own Info sheet says "Total Records: 566"; this file contains 526 data rows. 40
// records are not in this export for whatever reason (a filter, a page limit, a partial
// download). Whatever should have been the missing 40 will simply not be touched by this run —
// reported once at the top so it isn't mistaken for the sheet being complete.
//
// Usage:
//   node scripts/update-all-employees-from-report.mjs                        # dry run
//   node scripts/update-all-employees-from-report.mjs --dump-json             # rows out, no DB
//   node scripts/update-all-employees-from-report.mjs --apply                # write
//   node scripts/update-all-employees-from-report.mjs --apply --normalize-role-case
//   node scripts/update-all-employees-from-report.mjs --only-changed          # dry run, skip no-op rows in the printout

