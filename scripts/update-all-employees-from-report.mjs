// --- args ------------------------------------------------------------------
const args = process.argv.slice(2);
const APPLY = args.includes("--apply");
const DUMP_JSON = args.includes("--dump-json");
const NORMALIZE_ROLE_CASE = args.includes("--normalize-role-case");
const ONLY_CHANGED = args.includes("--only-changed");

const inr = (n) => "Rs " + Number(n || 0).toLocaleString("en-IN", { maximumFractionDigits: 2 });
const norm = (s) => (s || "").toString().trim().toLowerCase().replace(/\s+/g, " ");
const isBlank = (v) => v === undefined || v === null || String(v).trim() === "";

const HISTORICAL_BUCKETS = ["Agent", "Counsellor", "Doctor", "Technician", "Implanter", "Others", "Hr"];
function resolveRole(rawRole) {
  if (!NORMALIZE_ROLE_CASE) return rawRole;
  const hit = HISTORICAL_BUCKETS.find((b) => norm(b) === norm(rawRole));
  return hit && hit !== rawRole ? hit : rawRole;
}

if (DUMP_JSON) {
  fs.writeFileSync("all-employees-update-payload.json", JSON.stringify(ROWS, null, 2));
  console.log(`Wrote all-employees-update-payload.json — ${ROWS.length} row(s).`);
  process.exit(0);
}

if (!MONGODB_URI) {
  console.error("MONGODB_URI missing — checked .env.local and .env.");
  process.exit(1);
}

function validate() {
  const errors = [];
  for (const r of ROWS) {
    const where = `row ${r.rowNum} (${r.name})`;
    if (!/^[0-9a-fA-F]{24}$/.test(r.recordId || "")) errors.push(`${where}: "${r.recordId}" is not a valid Record ID`);
    if (!r.name) errors.push(`${where}: name is blank`);
  }
  return errors;
}

async function run() {
  console.log("=".repeat(94));
  console.log(APPLY ? "MODE: APPLY  <- will write to the database" : "MODE: DRY RUN  <- nothing will be written");
  console.log(`Rows in file: ${ROWS.length}   (report's own "Total Records" says 566 — 40 are not in this export)`);
  console.log(`Role casing : ${NORMALIZE_ROLE_CASE ? "historical-bucket names title-cased" : "written exactly as given (pass --normalize-role-case to change this)"}`);
  console.log("=".repeat(94) + "\n");

  const errors = validate();
  if (errors.length) {
    console.error(`VALIDATION FAILED — ${errors.length} problem(s). Nothing imported.\n`);
    errors.forEach((e) => console.error("  " + e));
    process.exit(1);
  }
  console.log("Validation passed.\n");

  const mergedCount = ROWS.filter((r) => r.isMerged).length;
  console.log(`[MERGED] marker rows in this file: ${mergedCount} (see header note — updated normally, not skipped)\n`);

  const caseCollisions = ROWS.filter((r) => HISTORICAL_BUCKETS.some((b) => norm(b) === norm(r.role) && b !== r.role));
  if (caseCollisions.length) {
    console.log("!".repeat(94));
    console.log(`CASE COLLISION WARNING — ${caseCollisions.length} row(s) have a Role that differs from a historical`);
    console.log("role-bucket name ONLY in case. A case-sensitive query on the old bucket name will not match");
    console.log("these unless you pass --normalize-role-case.");
    console.log("!".repeat(94));
    caseCollisions.slice(0, 15).forEach((r) => console.log(`  row ${r.rowNum}  ${r.name.padEnd(28)} "${r.role}"  vs historical "${HISTORICAL_BUCKETS.find((b) => norm(b) === norm(r.role))}"`));
    if (caseCollisions.length > 15) console.log(`  ... and ${caseCollisions.length - 15} more (full list is in the report file)`);
    console.log("");
  }

  await mongoose.connect(MONGODB_URI, { serverSelectionTimeoutMS: 8000 });
  const Employee = mongoose.models.Employee || mongoose.model("Employee", new mongoose.Schema({}, { strict: false, collection: "employees" }));

  console.log("Resolving each row by Record ID (_id) and diffing fields...\n");
  const toUpdate = [];
  const upToDate = [];
  const notFound = [];

  for (const r of ROWS) {
    const emp = await Employee.findById(r.recordId).select("_id employeeId name role email phone isactive salaryStructure incentiveRate").lean();
    if (!emp) { notFound.push(r); continue; }

    const changes = [];
    if (!isBlank(r.employeeId) && (emp.employeeId || "") !== r.employeeId) changes.push({ field: "employeeId", from: emp.employeeId || "", to: r.employeeId });
    if (!isBlank(r.name) && norm(emp.name) !== norm(r.name)) changes.push({ field: "name", from: emp.name, to: r.name });
    if (!isBlank(r.role)) {
      const role = resolveRole(r.role);
      if (emp.role !== role) changes.push({ field: "role", from: emp.role, to: role });
    }
    if (!isBlank(r.email) && norm(emp.email) !== norm(r.email)) changes.push({ field: "email", from: emp.email || "", to: r.email });
    if (!isBlank(r.phone) && (emp.phone || "") !== r.phone) changes.push({ field: "phone", from: emp.phone || "", to: r.phone });
    if (Boolean(emp.isactive) !== r.isactive) changes.push({ field: "isactive", from: emp.isactive, to: r.isactive });
    if (!isBlank(r.baseSalary) && Number(emp.salaryStructure?.baseSalary || 0) !== Number(r.baseSalary))
      changes.push({ field: "salaryStructure.baseSalary", from: emp.salaryStructure?.baseSalary ?? 0, to: Number(r.baseSalary) });
    if (!isBlank(r.salaryType) && (emp.salaryStructure?.salaryType || "Monthly") !== r.salaryType)
      changes.push({ field: "salaryStructure.salaryType", from: emp.salaryStructure?.salaryType, to: r.salaryType });
    if (r.effectiveFrom) {
      const oldEff = emp.salaryStructure?.effectiveFrom ? new Date(emp.salaryStructure.effectiveFrom).toISOString().slice(0, 10) : null;
      if (oldEff !== r.effectiveFrom) changes.push({ field: "salaryStructure.effectiveFrom", from: oldEff, to: r.effectiveFrom });
    }
    if (!isBlank(r.incentiveRate) && Number(emp.incentiveRate || 0) !== Number(r.incentiveRate))
      changes.push({ field: "incentiveRate", from: emp.incentiveRate ?? 0, to: Number(r.incentiveRate) });

    if (!changes.length) { upToDate.push({ r, emp }); continue; }
    toUpdate.push({ r, emp, changes });
  }

  console.log(`  Will update      : ${toUpdate.length}`);
  console.log(`  Already up to date: ${upToDate.length}`);
  console.log(`  Record ID not found: ${notFound.length}`);

  if (notFound.length) {
    console.log("\n--- RECORD ID NOT FOUND (skipped — deleted since the report was generated?) ---");
    notFound.forEach((r) => console.log(`  row ${r.rowNum}  ${r.name}  (${r.recordId})`));
  }

  if (toUpdate.length) {
    console.log(`\n--- ${ONLY_CHANGED || !APPLY ? "WILL UPDATE" : "UPDATES"} ---`);
    toUpdate.forEach(({ r, emp, changes }) => {
      console.log(`  row ${r.rowNum}  "${r.name}"  ->  ${emp._id}  (${changes.length} field(s))`);
      changes.forEach((c) => console.log(`      ${c.field}: ${JSON.stringify(c.from)}  ->  ${JSON.stringify(c.to)}`));
    });
  }

  if (!toUpdate.length) {
    console.log("\nNothing to update.");
    await mongoose.disconnect();
    return;
  }

  if (!APPLY) {
    console.log("\nDRY RUN — nothing written. Re-run with --apply once the lists above look right.");
    await mongoose.disconnect();
    return;
  }

  console.log(`\nUpdating ${toUpdate.length} employee(s)...`);
  const updated = [];
  const failed = [];

  for (const { r, emp, changes } of toUpdate) {
    try {
      const setFields = {};
      changes.forEach((c) => {
        if (c.field.startsWith("salaryStructure.")) {
          const sub = c.field.split(".")[1];
          setFields[`salaryStructure.${sub}`] = sub === "effectiveFrom" ? new Date(c.to) : c.to;
        } else {
          setFields[c.field] = c.field === "isactive" ? Boolean(c.to) : c.to;
        }
      });
      await Employee.updateOne({ _id: emp._id }, { $set: setFields });
      updated.push({ rowNum: r.rowNum, name: r.name, id: String(emp._id), changes });
      console.log(`  row ${String(r.rowNum).padStart(4)}  ${r.name.padEnd(28)}  UPDATED (${emp._id}) — ${changes.length} field(s)`);
    } catch (err) {
      failed.push({ rowNum: r.rowNum, name: r.name, reason: err?.message || String(err) });
      console.log(`  row ${String(r.rowNum).padStart(4)}  ${r.name.padEnd(28)}  FAILED: ${err?.message || err}`);
    }
  }

  console.log(`\nUpdated ${updated.length}, failed ${failed.length}.`);

  const reportPath = `all-employees-update-report-${Date.now()}.json`;
  fs.writeFileSync(
    reportPath,
    JSON.stringify(
      {
        updated, failed,
        notFound: notFound.map((r) => ({ rowNum: r.rowNum, name: r.name, recordId: r.recordId })),
        caseCollisions: caseCollisions.map((r) => ({ rowNum: r.rowNum, name: r.name, role: r.role })),
      },
      null,
      2,
    ),
  );
  console.log(`\nReport written to ${reportPath} — keep it, the before-values are your undo list.`);

  await mongoose.disconnect();
  console.log("Done.");
}

run().catch(async (err) => {
  console.error("\nFATAL:", err);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
